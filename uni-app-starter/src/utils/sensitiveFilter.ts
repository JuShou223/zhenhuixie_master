const SENSITIVE_SET: Set<string> = new Set(sensitiveWords)

export function hasSensitiveWord(text: string | null | undefined): boolean {
  if (!text) return false
  for (const word of SENSITIVE_SET) {
    if (text.includes(word)) return true
  }
  return false
}

export function filterSensitiveWord(text: string | null | undefined): string {
  if (!text) return text ?? ''
  let result = text
  for (const word of SENSITIVE_SET) {
    if (result.includes(word)) {
      result = result.replaceAll(word, '*'.repeat(word.length))
    }
  }
  return result
}
